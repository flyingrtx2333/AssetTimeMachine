#!/usr/bin/env python3
"""Small pre-defined meta-risk factor lab for the frozen C3/L3 strategy.

The input panel is generated by cash_confidence_nfci_c3_l3_state_dump.swiftpart.
Every feature at row T uses only data through T close; labels start after T.
The lab intentionally keeps the feature family small to reduce data mining.
"""
from __future__ import annotations

import csv
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import daily_alpha_factor_lab as stat  # noqa: E402

DEV_END = "2014-12-31"
VAL_END = "2020-12-31"
HORIZONS = (5, 20, 60)
ASSETS = ("gold", "nasdaq", "sp500", "csi300", "shanghai")


def read_panel(path: Path):
    rows = list(csv.DictReader(path.open(newline="", encoding="utf-8")))
    dates = [row["date"] for row in rows]
    cols: dict[str, list[float]] = {}
    for key in rows[0]:
        if key in {"date", "overlay_signal_date"}:
            continue
        vals = []
        for row in rows:
            try:
                vals.append(float(row[key]))
            except (TypeError, ValueError):
                vals.append(float("nan"))
        cols[key] = vals
    return dates, cols


def daily_returns(values):
    out = [None] * len(values)
    for i in range(1, len(values)):
        if values[i - 1] > 0 and math.isfinite(values[i]) and math.isfinite(values[i - 1]):
            out[i] = values[i] / values[i - 1] - 1.0
    return out


def rolling_std(values, window):
    out = [None] * len(values)
    for i in range(window, len(values)):
        xs = values[i - window + 1 : i + 1]
        if any(x is None or not math.isfinite(x) for x in xs):
            continue
        out[i] = stat.stdev([float(x) for x in xs]) * math.sqrt(252.0)
    return out


def rolling_drawdown(values, window):
    out = [None] * len(values)
    for i in range(window - 1, len(values)):
        xs = values[i - window + 1 : i + 1]
        if min(xs) <= 0:
            continue
        out[i] = values[i] / max(xs) - 1.0
    return out


def pct_change(values, window):
    out = [None] * len(values)
    for i in range(window, len(values)):
        if values[i - window] > 0:
            out[i] = values[i] / values[i - window] - 1.0
    return out


def rolling_percentile_sparse(values, window=756, minimum=252):
    out = [None] * len(values)
    for i in range(len(values)):
        start = max(0, i - window + 1)
        xs = [x for x in values[start : i + 1] if x is not None and math.isfinite(x)]
        current = values[i]
        if current is None or not math.isfinite(current) or len(xs) < minimum:
            continue
        less = sum(x < current for x in xs)
        equal = sum(x == current for x in xs)
        out[i] = (less + 0.5 * equal) / len(xs)
    return out


def pair_ratio(a, b):
    out = [None] * len(a)
    for i, (x, y) in enumerate(zip(a, b)):
        if x is not None and y is not None and abs(y) > 1e-12:
            out[i] = x / y
    return out


def breadth(prices, window):
    moms = {asset: pct_change(prices[asset], window) for asset in ASSETS}
    out = [None] * len(next(iter(prices.values())))
    for i in range(len(out)):
        xs = [moms[asset][i] for asset in ASSETS]
        if any(x is None for x in xs):
            continue
        out[i] = sum(float(x) > 0 for x in xs) / len(xs)
    return out


def forward_return(values, h):
    out = [None] * len(values)
    for i in range(len(values) - h):
        if values[i] > 0:
            out[i] = values[i + h] / values[i] - 1.0
    return out


def forward_path_loss(values, h):
    """Positive worst loss from T close over the next h sessions."""
    out = [None] * len(values)
    for i in range(len(values) - h):
        if values[i] <= 0:
            continue
        trough = min(values[i + 1 : i + h + 1])
        out[i] = max(1.0 - trough / values[i], 0.0)
    return out


def forward_vol(values, h):
    rets = daily_returns(values)
    out = [None] * len(values)
    for i in range(len(values) - h):
        xs = rets[i + 1 : i + h + 1]
        if any(x is None or not math.isfinite(x) for x in xs) or len(xs) < 2:
            continue
        out[i] = stat.stdev([float(x) for x in xs]) * math.sqrt(252.0)
    return out


def forward_sharpe(values, h):
    rets = daily_returns(values)
    out = [None] * len(values)
    for i in range(len(values) - h):
        xs = rets[i + 1 : i + h + 1]
        if any(x is None or not math.isfinite(x) for x in xs) or len(xs) < 3:
            continue
        sample = [float(x) for x in xs]
        sd = stat.stdev(sample)
        if sd > 1e-12:
            out[i] = stat.mean(sample) / sd * math.sqrt(252.0)
    return out


def valid_xy(dates, x, y, split):
    xs, ys = [], []
    for d, a, b in zip(dates, x, y):
        if a is None or b is None or not math.isfinite(a) or not math.isfinite(b):
            continue
        if split == "dev" and d > DEV_END:
            continue
        if split == "validation" and not (DEV_END < d <= VAL_END):
            continue
        if split == "holdout" and d <= VAL_END:
            continue
        xs.append(float(a)); ys.append(float(b))
    return xs, ys


def eval_feature(dates, feature, label, h):
    result = {}
    for split in ("dev", "validation", "holdout"):
        x, y = valid_xy(dates, feature, label, split)
        result[split] = stat.nw_univariate(x, y, max(h - 1, 0)) if len(x) >= 80 else None
    return result


def beta_text(result):
    if result is None:
        return "n/a"
    return f"{result.beta:+.6f}/{result.beta_t:+.2f}"


def bucket_summary(dates, feature, labels, title):
    # Fixed natural percentiles rather than optimized thresholds.
    for threshold in (0.80, 0.90):
        print(f"STATE {title}>={threshold:.2f}")
        for split in ("dev", "validation", "holdout"):
            indices = []
            for i, (d, x) in enumerate(zip(dates, feature)):
                if x is None or not math.isfinite(x) or x < threshold:
                    continue
                if split == "dev" and d > DEV_END: continue
                if split == "validation" and not (DEV_END < d <= VAL_END): continue
                if split == "holdout" and d <= VAL_END: continue
                indices.append(i)
            parts = [split, f"n={len(indices)}"]
            for name, arr in labels.items():
                vals = [arr[i] for i in indices if arr[i] is not None and math.isfinite(arr[i])]
                parts.append(f"{name}={sum(vals)/len(vals):+.5f}" if vals else f"{name}=n/a")
            print(" ".join(parts))


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/private/tmp/c3l3_state_panel.csv")
    dates, cols = read_panel(path)
    pv = cols["portfolio_value"]
    ret1 = daily_returns(pv)
    rv20 = rolling_std(ret1, 20)
    rv63 = rolling_std(ret1, 63)
    rv252 = rolling_std(ret1, 252)
    vol_ratio = pair_ratio(rv20, rv252)
    features = {
        "rvol20": rv20,
        "rvol63": rv63,
        "rvol20_pct756": rolling_percentile_sparse(rv20),
        "vol_ratio20_252": vol_ratio,
        "vol_ratio_pct756": rolling_percentile_sparse(vol_ratio),
        "equity_dd63": rolling_drawdown(pv, 63),
        "equity_dd252": rolling_drawdown(pv, 252),
        "breadth252": breadth({asset: cols[f"price_{asset}"] for asset in ASSETS}, 252),
    }

    print("C3L3_META_RISK_LAB")
    print(f"rows={len(dates)} start={dates[0]} end={dates[-1]}")
    print("feature,label,horizon,dev_beta/t,val_beta/t,hold_beta/t,stable")
    labels_by_h = {}
    for h in HORIZONS:
        labels = {
            "return": forward_return(pv, h),
            "loss": forward_path_loss(pv, h),
            "vol": forward_vol(pv, h),
            "sharpe": forward_sharpe(pv, h),
        }
        labels_by_h[h] = labels
        for feature_name, feature in features.items():
            for label_name, label in labels.items():
                r = eval_feature(dates, feature, label, h)
                dev, val, hold = r["dev"], r["validation"], r["holdout"]
                stable = int(
                    dev is not None and val is not None and hold is not None
                    and dev.beta * val.beta > 0 and dev.beta * hold.beta > 0
                )
                print(",".join([
                    feature_name, label_name, str(h), beta_text(dev), beta_text(val), beta_text(hold), str(stable)
                ]))

    # Only two predeclared state variables get bucket diagnostics.
    natural_labels = {
        "ret20": labels_by_h[20]["return"],
        "loss20": labels_by_h[20]["loss"],
        "sharpe20": labels_by_h[20]["sharpe"],
        "ret60": labels_by_h[60]["return"],
        "loss60": labels_by_h[60]["loss"],
        "sharpe60": labels_by_h[60]["sharpe"],
    }
    print("UNCONDITIONAL")
    for split in ("dev", "validation", "holdout"):
        parts = [split]
        for name, arr in natural_labels.items():
            _, vals = valid_xy(dates, [0.0] * len(dates), arr, split)
            parts.append(f"{name}={sum(vals)/len(vals):+.5f}" if vals else f"{name}=n/a")
        print(" ".join(parts))
    bucket_summary(dates, features["rvol20_pct756"], natural_labels, "rvol20_pct756")
    bucket_summary(dates, features["vol_ratio_pct756"], natural_labels, "vol_ratio_pct756")


if __name__ == "__main__":
    main()
