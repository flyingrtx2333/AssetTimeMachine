#!/usr/bin/env python3
"""Install an audited --catalog-metrics result as shared iOS/macOS presentation data.

Inputs must come from AssetTimeMachineMetricDump --catalog-metrics. Trading parameters,
historical diagnostic costs and strategy selection are never changed by this tool.
"""
import argparse
import datetime as dt
import json
import math
import os
from pathlib import Path
import subprocess
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Sources/AssetTimeMachineBacktestCore/Domain/StrategyCatalogMetrics.generated.swift"
RECEIPT = ROOT / "tools/expected_backtest_metrics/app/strategy_catalog_metrics.json"


def refresh():
    import refresh_app_backtest_baseline as baseline

    fixtures = ROOT / "tools/fixtures/backtest-history"
    history_path = fixtures / "public_history.json"
    history = baseline.fetch_fixture(history_path, 120)

    def download(url, path):
        request = urllib.request.Request(url, headers={"Accept": "application/json", "Cache-Control": "no-cache"})
        with urllib.request.urlopen(request, timeout=120) as response:
            raw = response.read()
        document = json.loads(raw)
        if document.get("success") is not True:
            raise ValueError(f"Public data request failed: {url}")
        baseline.atomic_write(path, raw)
        return document

    macro_path = fixtures / "nfci-asof.json"
    download("https://api.flyingrtx.com/api/v1/money/public/nfci-asof", macro_path)
    query = urllib.parse.urlencode({"symbols": "qual", "period": "all", "include_ohlc": "true"})
    supplement = download(baseline.ENDPOINT + "?" + query, fixtures / "catalog-supplement.json")
    binary = ROOT / "build/strategy-catalog-metric-dump"
    baseline.compile_metric_dump(binary, 1800)

    # Preserve the separate historical 1% / 0.05% regression contract.
    os.environ["ATM_NFCI_ASOF_FIXTURE"] = str(macro_path)
    os.environ["ATM_FEE_RATE_PERCENT"] = "1"
    os.environ["ATM_SLIPPAGE_RATE_PERCENT"] = "0.05"
    slices = baseline.collect_slice_rows(binary, history_path, 1800)
    baseline.update_baseline(baseline.DEFAULT_BASELINE, history, slices)

    combined = dict(history)
    symbols = {row["symbol"] for row in history["series"]}
    combined["series"] = history["series"] + [row for row in supplement["series"] if row["symbol"] not in symbols]
    combined_path = ROOT / "build/catalog-history.json"
    baseline.atomic_write(combined_path, json.dumps(combined, ensure_ascii=False, separators=(",", ":")).encode())
    result = subprocess.run([str(binary), "--catalog-metrics", "--history", str(combined_path),
                             "--macro", str(macro_path)], cwd=ROOT, capture_output=True, text=True, timeout=1800)
    print(result.stderr, end="")
    result.check_returncode()
    return json.loads(result.stdout)


def render(document):
    if document.get("schema") != "app-strategy-catalog-metrics-v1":
        raise ValueError("Expected the maintained --catalog-metrics output")
    rows = document["strategies"]
    ids = [row["id"] for row in rows]
    if not ids or len(ids) != len(set(ids)):
        raise ValueError("Empty or duplicate strategy IDs")
    for row in rows:
        if row.get("status") != "ready":
            raise ValueError(f"No verified metrics for {row['id']}: {row.get('status')}")
        for name in ("annualized_return", "max_drawdown", "sharpe_ratio", "fee_percent", "slippage_percent"):
            if not math.isfinite(row[name]):
                raise ValueError(f"Nonfinite {name}: {row['id']}")
        if not -1 <= row["annualized_return"] or not 0 <= row["max_drawdown"] <= 1:
            raise ValueError(f"Invalid return/drawdown: {row['id']}")
        if row["fee_percent"] < 0 or row["slippage_percent"] < 0 or row["points"] < 2:
            raise ValueError(f"Invalid cost/history: {row['id']}")
        if dt.date.fromisoformat(row["start"]) >= dt.date.fromisoformat(row["end"]):
            raise ValueError(f"Invalid period: {row['id']}")
    ends = {row["end"] for row in rows}
    if len(ends) != 1:
        raise ValueError("Catalog rows need one common cutoff; retain each actual start date")
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    lines = [
        "// Generated by scripts/update_strategy_catalog_metrics.py. Do not hand-edit.",
        "// Historical App-engine replays; these figures do not imply formal validation.",
        "import Foundation", "",
        "public struct StrategyCatalogMetric: Sendable {",
        "    public let annualizedReturn: Double",
        "    public let maxDrawdown: Double",
        "    public let sharpeRatio: Double",
        "    public let startDate: String",
        "    public let endDate: String",
        "    public let feePercent: Double",
        "    public let slippagePercent: Double",
        "    public let strategyVersion: String", "}", "",
        "public enum StrategyCatalogMetrics {",
        f"    public static let engineVersion = {quote(document['engine_version'])}",
        f"    public static let generatedAt = {quote(document['generated_at'])}",
        f"    public static let asOfDate = {quote(next(iter(ends)))}",
        f"    public static let historySHA256 = {quote(document['history_sha256'])}",
        f"    public static let macroSHA256 = {quote(document['macro_sha256'])}",
        "    public static let entries: [String: StrategyCatalogMetric] = [",
    ]
    for row in rows:
        lines.append(f"        {quote(row['id'])}: .init(annualizedReturn: {row['annualized_return']!r}, "
                     f"maxDrawdown: {row['max_drawdown']!r}, sharpeRatio: {row['sharpe_ratio']!r}, "
                     f"startDate: {quote(row['start'])}, endDate: {quote(row['end'])}, "
                     f"feePercent: {row['fee_percent']!r}, slippagePercent: {row['slippage_percent']!r}, "
                     f"strategyVersion: {quote(row['strategy_version'])}),")
    return "\n".join(lines + ["    ]", "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, nargs="?")
    parser.add_argument("--refresh", action="store_true", help="Fetch current public inputs and replay existing catalog/defaults")
    parser.add_argument("--check", action="store_true", help="Validate reproducibility without writing")
    args = parser.parse_args()
    if args.refresh and (args.input or args.check):
        parser.error("--refresh cannot be combined with an input or --check")
    if not args.refresh and args.input is None:
        parser.error("Provide the maintained CLI result, or use --refresh")
    if os.environ.get("ATM_APP_STRATEGY_ID"):
        parser.error("Clear ATM_APP_STRATEGY_ID; catalog refresh must include every product strategy")
    document = refresh() if args.refresh else json.loads(args.input.read_text())
    source = render(document)
    if args.check:
        if SOURCE.read_text() != source:
            raise SystemExit("Generated catalog source differs from the receipt")
    else:
        SOURCE.write_text(source)
        RECEIPT.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n")
    print(f"Verified catalog: {len(document['strategies'])} strategies through {document['strategies'][0]['end']}")


if __name__ == "__main__":
    main()
